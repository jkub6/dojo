import logging
from pathlib import Path

from tqdm import tqdm

from .config import Config, CustomRule, OutputConfig
from .constants import PoolName, RuleName
from .plugins import PluginInterface, load_plugin
from .rules import get_builtin_rules
from .utils import (
    get_recursive_yaml_deps,
    ninja_escape,
    parse_frontmatter_type,
    sanitize_path,
    should_process_file,
)


logger = logging.getLogger(__name__)


class NinjaGenerator:
    """
    Generates Ninja build files for a static site pipeline.

    The build process has these stages:
    1. Compile: Markdown → JSON (Pandoc AST)
    2. Render: JSON → Output format (HTML, PDF, etc)
    3. Post-process: Output → Optimized (minify, compress)
    4. Derive: Output → Derived format (HTML → PDF via Decktape)
    """

    def __init__(self, config: Config, config_path: Path):
        self.config = config
        self.config_path = config_path.resolve()

        # Configure paths
        self.src = Path(self.config.src_dir).resolve()
        self.out_dir = Path(self.config.output_dir).resolve()
        self.build_dir = Path(self.config.build_dir).resolve()
        self.ninja_file = self.build_dir / "build.ninja"

        # Create build directory
        self.build_dir.mkdir(parents=True, exist_ok=True)

        # Output buffer for Ninja file
        self.buffer: list[str] = []

        # Track all final outputs
        self.all_outputs: list[Path] = []

        # Load plugins
        self.plugins: list[PluginInterface] = []
        for plugin_path in self.config.plugins:
            plugin = load_plugin(plugin_path)
            if plugin:
                self.plugins.append(plugin)

        # Collect rules: Built-in + Config Custom + Plugin Custom
        self.rules: list[CustomRule] = get_builtin_rules(self.config, self.config_path)
        self.rules.extend(self.config.custom_rules)
        for plugin in self.plugins:
            self.rules.extend(plugin.get_custom_rules())

    def write(self, line: str = "") -> None:
        """Add a line to the Ninja file buffer."""
        self.buffer.append(line)

    def emit_header(self) -> None:
        """Generate Ninja file header with version, pools, and rules."""
        self.write("# Auto-generated by dojo - DO NOT EDIT MANUALLY")
        self.write(f"# Source: {self.config_path}")
        self.write()
        self.write("ninja_required_version = 1.3")
        self.write()

        # Pools
        self.write("# Resource pools prevent CPU/memory saturation")
        self.write(f"pool {PoolName.HEAVY_PROCESSING.value}")
        self.write("  depth = 1")
        self.write()

        # Rules
        self.write("# Rules")
        for rule in self.rules:
            self.write(f"rule {rule.name}")
            self.write(f"  command = {rule.command}")
            if rule.description:
                self.write(f"  description = {rule.description}")
            if rule.pool:
                self.write(f"  pool = {rule.pool}")
            if rule.depfile:
                self.write(f"  depfile = {rule.depfile}")
            if rule.deps:
                self.write(f"  deps = {rule.deps}")
            if rule.generator:
                self.write("  generator = 1")
            self.write()

            # Special case for REGENERATE: emit the build edge immediately
            if rule.name == RuleName.REGENERATE.value:
                self.write(
                    f"build {ninja_escape(self.ninja_file)}: {RuleName.REGENERATE.value} {ninja_escape(self.config_path)}"
                )
                self.write()

    def process_content(self, md_path: Path) -> None:
        """
        Generate Ninja build rules for a single Markdown source file.
        """
        # Calculate relative path structure and sanitize
        try:
            rel_path = md_path.relative_to(self.src)
        except ValueError:
            logger.error(f"Source file outside source directory: {md_path}")
            return

        rel_stem = rel_path.with_suffix("")

        # Stage 1: Compile to JSON
        json_node = sanitize_path(self.build_dir, rel_stem.with_suffix(".json"))

        self.write(f"# Source: {md_path.relative_to(Path.cwd())}")
        self.write(
            f"build {ninja_escape(json_node)}: {RuleName.COMPILE.value} {ninja_escape(md_path)}"
        )
        self.write()

        # Determine content type from frontmatter
        content_type = parse_frontmatter_type(md_path, self.config.default_type)
        type_config = self.config.types.get(
            content_type, self.config.types[self.config.default_type]
        )

        if not type_config.outputs:
            return

        # Local registry tracks outputs for THIS specific file
        local_registry: dict[str, Path] = {}

        # Process each configured output
        for out_config in type_config.outputs:
            # Allow plugins to modify output configuration
            for plugin in self.plugins:
                out_config = plugin.modify_output_config(out_config, content_type)

            self._process_output(out_config, rel_stem, json_node, local_registry)

        self.write()

    def _process_output(
        self,
        out_config: OutputConfig,
        rel_stem: Path,
        json_node: Path,
        local_registry: dict[str, Path],
    ) -> None:
        """
        Generate Ninja rules for a single output format.
        """
        out_id = out_config.id
        ext = out_config.extension
        suffix = out_config.suffix

        # Construct output filename and sanitize path
        filename = f"{rel_stem.name}{suffix}.{ext}"
        try:
            final_path = sanitize_path(self.out_dir, rel_stem.parent / filename)
        except ValueError as e:
            logger.error(f"Path validation failed: {e}")
            return

        # Derived Output
        if out_config.source:
            parent_id = out_config.source
            tool = out_config.tool

            # Validate the source output exists
            if parent_id not in local_registry:
                logger.error(
                    f"Output '{out_id}' depends on '{parent_id}' which hasn't been defined"
                )
                logger.error(f"File: {rel_stem}")
                raise ValueError(f"Missing dependency: {parent_id}")

            source_file = local_registry[parent_id]

            self.write(f"build {ninja_escape(final_path)}: {tool} {ninja_escape(source_file)}")

            if out_id:
                local_registry[out_id] = final_path

            self.all_outputs.append(final_path)
            return

        # Standard Render
        post_tool = out_config.post_process

        if post_tool:
            try:
                render_target = sanitize_path(
                    self.build_dir, Path("intermediates") / rel_stem.parent / filename
                )
            except ValueError as e:
                logger.error(f"Path validation failed for intermediate: {e}")
                return
        else:
            render_target = final_path

        # Gather dependencies
        defaults_file = Path(out_config.defaults)

        try:
            deps = [defaults_file, *get_recursive_yaml_deps(defaults_file)]
            dep_paths = sorted(set(deps))
            dep_str = " ".join(ninja_escape(d) for d in dep_paths)
        except ValueError as e:
            logger.error(f"Dependency resolution failed: {e}")
            raise

        # Generate render rule
        self.write(
            f"build {ninja_escape(render_target)}: {RuleName.RENDER.value} {ninja_escape(json_node)} | {dep_str}"
        )
        self.write(f"  defaults = {ninja_escape(defaults_file)}")
        self.write()

        # Post-Processing
        if post_tool:
            self.write(
                f"build {ninja_escape(final_path)}: {post_tool} {ninja_escape(render_target)}"
            )
            self.write()

            if out_id:
                local_registry[out_id] = final_path
        else:
            if out_id:
                local_registry[out_id] = render_target

        self.all_outputs.append(final_path)

    def generate(self) -> None:
        """
        Main execution: scan source files and generate build.ninja.
        """
        logger.info(f"Scanning source directory: {self.src}")

        self.emit_header()

        md_files = sorted(self.src.rglob("*.md"))

        # Filter files based on include/exclude patterns
        filtered_files = []
        for md_file in md_files:
            if should_process_file(
                md_file, self.src, self.config.include, self.config.exclude
            ):
                filtered_files.append(md_file)
            else:
                logger.debug(f"Skipping excluded file: {md_file}")

        md_files = filtered_files

        if not md_files:
            logger.warning(f"No Markdown files found in {self.src}")
        else:
            logger.info(f"Found {len(md_files)} Markdown file(s)")

        # Process each file with progress bar
        for md_file in tqdm(md_files, desc="Processing", unit="file"):
            try:
                self.process_content(md_file)
            except Exception as e:
                logger.error(f"Failed to process {md_file}: {e}")
                raise

        ninja_content = "\n".join(self.buffer)

        # Allow plugins to post-process
        for plugin in self.plugins:
            ninja_content = plugin.post_process_ninja(ninja_content)

        try:
            with open(self.ninja_file, "w", encoding="utf-8") as f:
                f.write(ninja_content)
        except Exception as e:
            logger.error(f"Failed to write {self.ninja_file}: {e}")
            raise

        logger.info(f"Generated: {self.ninja_file}")
        logger.info(f"Outputs: {len(self.all_outputs)} file(s) will be built")
        logger.info("")
        logger.info("Next steps:")
        logger.info(f"  ninja -f {self.ninja_file.relative_to(Path.cwd())}")
